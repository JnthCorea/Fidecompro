    private void cmbTipoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmbTipoActionPerformed
        
        String tipo = cmbTipo.getSelectedItem().toString();

        if (tipo.equals("Alimenticio")) {
            lblDetalle.setText("Fecha de vencimiento");

        } else if (tipo.equals("Limpieza")) {
            lblDetalle.setText("Presentación");

        } else if (tipo.equals("Hogar")) {
            lblDetalle.setText("Material");
        }
    }//GEN-LAST:event_cmbTipoActionPerformed

    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        
        try {

            String codigo = txtCodigo.getText();
            String nombre = txtNombre.getText();
            String descripcion = txtDescripcion.getText();
            double precio = Double.parseDouble(txtPrecio.getText());
            int cantidad = Integer.parseInt(txtCantidad.getText());

            String tipo = cmbTipo.getSelectedItem().toString();
            String detalle = txtDetalle.getText();

            Producto nuevoProducto;

            if (tipo.equals("Alimenticio")) {

                nuevoProducto = new ProductoAlimenticio(
                        codigo,
                        nombre,
                        descripcion,
                        precio,
                        cantidad,
                        detalle
                );

            } else if (tipo.equals("Limpieza")) {

                nuevoProducto = new ProductoLimpieza(
                        codigo,
                        nombre,
                        descripcion,
                        precio,
                        cantidad,
                        detalle
                );

            } else {

                nuevoProducto = new ProductoHogar(
                        codigo,
                        nombre,
                        descripcion,
                        precio,
                        cantidad,
                        detalle
                );
            }

            fidecompro.inventario.agregarProducto(nuevoProducto);

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Producto agregado correctamente"
            );

            txtCodigo.setText("");
            txtNombre.setText("");
            txtDescripcion.setText("");
            txtPrecio.setText("");
            txtCantidad.setText("");
            txtDetalle.setText("");

        } catch (NumberFormatException e) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Precio y cantidad deben contener valores numéricos"
            );
        }
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        
        String codigo = txtCodigo.getText();

        try {

            Producto producto =
                    fidecompro.inventario.buscarProducto(codigo);

            txtNombre.setText(producto.getNombre());
            txtDescripcion.setText(producto.getDescripcion());
            txtPrecio.setText(String.valueOf(producto.getPrecio()));
            txtCantidad.setText(String.valueOf(producto.getCantidadDisponible()));

            cmbTipo.setSelectedItem(producto.obtenerTipo());

            if (producto instanceof ProductoAlimenticio) {

                ProductoAlimenticio alimenticio =
                        (ProductoAlimenticio) producto;

                txtDetalle.setText(alimenticio.getFechaVencimiento());

            } else if (producto instanceof ProductoLimpieza) {

                ProductoLimpieza limpieza =
                        (ProductoLimpieza) producto;

                txtDetalle.setText(limpieza.getPresentacion());

            } else if (producto instanceof ProductoHogar) {

                ProductoHogar hogar =
                        (ProductoHogar) producto;

                txtDetalle.setText(hogar.getMaterial());
            }

        } catch (ProductoNoEncontradoException e) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    e.getMessage()
            );
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnActualizarExistenciaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarExistenciaActionPerformed
        
        try {

            String codigo = txtCodigo.getText();
            int cantidad = Integer.parseInt(txtCantidad.getText());

            fidecompro.inventario.actualizarExistencia(
                    codigo,
                    cantidad
            );

            Producto producto =
                    fidecompro.inventario.buscarProducto(codigo);

            txtCantidad.setText(
                    String.valueOf(producto.getCantidadDisponible())
            );

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Existencia actualizada correctamente"
            );

        } catch (NumberFormatException e) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "La cantidad debe ser un número"
            );

        } catch (ProductoNoEncontradoException e) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    e.getMessage()
            );
        }
    }//GEN-LAST:event_btnActualizarExistenciaActionPerformed

